export const seasons = [
  { id: 'spring', name: '봄', months: '3–5월', mark: '새로 피어나는' },
  { id: 'summer', name: '여름', months: '6–8월', mark: '초록이 깊어지는' },
  { id: 'autumn', name: '가을', months: '9–11월', mark: '색으로 물드는' },
  { id: 'winter', name: '겨울', months: '12–2월', mark: '하얗게 쉬어가는' },
] as const;
export type Season = (typeof seasons)[number]['id'];
export function seasonForDate(date: string): Season {
  const month = Number(date.slice(5, 7));
  return month >= 3 && month <= 5
    ? 'spring'
    : month >= 6 && month <= 8
      ? 'summer'
      : month >= 9 && month <= 11
        ? 'autumn'
        : 'winter';
}
